/**
 * REAL BUCHAREST, LAID UNDER THE GENERATED CITY.
 *
 * `src/content/bucharest.json` holds curated OpenStreetMap data for the centre
 * of the city — 1,100 building footprints with storey counts, 2,708 classified
 * street centrelines, 183 tram ways, 108 parks and 9 squares — already
 * projected to metres with +X east, +Z south and the origin on Piața
 * Universității. © OpenStreetMap contributors, ODbL 1.0.
 *
 * This module turns that survey into the game's own terms: a road graph, a
 * street-wall of oriented plots, green space, and an occupancy mask that the
 * rest of the city generator reads to know where the real city already is.
 * NO GEOMETRY IS IMPORTED. Every triangle is still generated by the game's
 * grammar; the data supplies layout, rhythm, orientation and height.
 *
 * ==================================================================
 * THE SCALE DECISION — read this before changing OSM_FIT
 * ==================================================================
 *
 * The OSM extent is about 3.7 km east-west by 4.6 km north-south. The game
 * world is `WorldScale.gridBlocks * blockSize` = 26 x 92 m = 2,392 m square.
 * The data does not fit, and the three squares the brief names are the reason:
 *
 *     Piața Victoriei      (-1300, -1845)      real metres from Universitate
 *     Piața Universității  (   -11,   -28)
 *     Piața Unirii         (     0,   870)
 *
 * Victoriei to the far side of Bulevardul Unirii is 2,919 m of north-south
 * alone, against a 2,392 m map. There is no offset that fits them at 1:1, so
 * the only honest choices are to drop one of the named squares or to compress.
 * WE COMPRESS, AND HERE IS EXACTLY BY HOW MUCH:
 *
 *     scale 0.60 — positions and building footprints only.
 *
 * Everything a human is measured against stays at true size: storey heights,
 * lane widths, pavements, doors, cars, lamp posts, the player. Only the map is
 * compressed, which is what every open-world game does with a real city (Los
 * Santos is roughly a tenth of Los Angeles). The consequence is that a block is
 * shorter than its real counterpart and streets are relatively wider — which is
 * the correct trade for a game you drive through.
 *
 * The offset is then forced, not chosen: it puts Piața Universității exactly on
 * the game's authored hero crossroads at (-92, 0). That single alignment buys:
 *
 *   - Bulevardul Magheru / Bălcescu / Brătianu becomes the authored N–S
 *     monumental axis (grid column 12, x = -92),
 *   - Bulevardul Regina Elisabeta / Carol I becomes the authored E–W axis
 *     (grid row 13, z = 0) to within 30 m along its whole run,
 *   - Casa Builderilor — the story's tower — ends up standing on Piața
 *     Universității, the square Romanian protest actually happens in,
 *   - Piața Victoriei lands at (-896, -1117), the north-west approach, and
 *     Piața Unirii at (-80, 530), both inside the map with margin.
 *
 * 859 of the 1,100 curated footprints and 128 km of real street fall inside the
 * map at this fit.
 *
 * The authored landmarks do NOT move. Where the survey and the story disagree
 * the story wins: real footprints, roads and parks are suppressed inside the
 * landmark voids and the plaza decks (`reserved` below), so Palatul
 * Parlamentului still closes the axis and the broadcast plaza is still there.
 *
 * Buildings are additionally grown about their own centroids by
 * `footprintGrow`, so a real 15 m frontage arrives as 12 m rather than 9.4 m.
 * Compressing positions without compensating the plots would have produced a
 * city of tall thin slivers with gaps between them; the growth is clamped per
 * building against the carriageway mask so nothing grows into a street.
 */

