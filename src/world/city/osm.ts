/** Fine mask cell size, metres. */
const CELL = 2;
/** Coverage mask cell size, metres. */
const COVER_CELL = 16;
/** How far from a real street the survey is considered to describe the city. */
const COVER_REACH = 78;

export const Cell = {
  road: 1,
  walk: 2,
  built: 4,
  green: 8,
  reserved: 16,
  square: 32,
  /** Within reach of a real boulevard — see CitySystem.district(). */
  major: 64,
} as const;

export class OccupancyMask {
  readonly n: number;
  readonly data: Uint8Array;
  private readonly cell: number;

  constructor(cell: number) {
    this.cell = cell;
    this.n = Math.ceil((WORLD_HALF * 2) / cell) + 2;
    this.data = new Uint8Array(this.n * this.n);
  }

  private ix(x: number): number {
    return Math.floor((x + WORLD_HALF) / this.cell) + 1;
  }

  at(x: number, z: number): number {
    const i = this.ix(x);
    const j = this.ix(z);
    if (i < 0 || j < 0 || i >= this.n || j >= this.n) return 0;
    return this.data[j * this.n + i];
  }

  has(x: number, z: number, bit: number): boolean {
    return (this.at(x, z) & bit) !== 0;
  }

  /** Stamp a capsule of the given width along a segment. */
  stampSegment(
    x0: number, z0: number, x1: number, z1: number, width: number, bit: number,
  ): void {
    const hw = width / 2;
    const i0 = this.ix(Math.min(x0, x1) - hw);
    const i1 = this.ix(Math.max(x0, x1) + hw);
    const j0 = this.ix(Math.min(z0, z1) - hw);
    const j1 = this.ix(Math.max(z0, z1) + hw);
    const dx = x1 - x0;
    const dz = z1 - z0;
    const len2 = dx * dx + dz * dz || 1;
    const hw2 = hw * hw;
    for (let j = Math.max(0, j0); j <= Math.min(this.n - 1, j1); j++) {
      const pz = (j - 1) * this.cell - WORLD_HALF + this.cell * 0.5;
      for (let i = Math.max(0, i0); i <= Math.min(this.n - 1, i1); i++) {
        const px = (i - 1) * this.cell - WORLD_HALF + this.cell * 0.5;
        let t = ((px - x0) * dx + (pz - z0) * dz) / len2;
        t = t < 0 ? 0 : t > 1 ? 1 : t;
        const ex = px - (x0 + dx * t);
        const ez = pz - (z0 + dz * t);
        if (ex * ex + ez * ez <= hw2) this.data[j * this.n + i] |= bit;
      }
    }
  }

  stampRect(cx: number, cz: number, w: number, d: number, rot: number, bit: number): void {
    const cs = Math.cos(rot);
    const sn = Math.sin(rot);
    const r = Math.hypot(w, d) / 2;
    const i0 = this.ix(cx - r);
    const i1 = this.ix(cx + r);
    const j0 = this.ix(cz - r);
    const j1 = this.ix(cz + r);
    const hw = w / 2;
    const hd = d / 2;
    for (let j = Math.max(0, j0); j <= Math.min(this.n - 1, j1); j++) {
      const pz = (j - 1) * this.cell - WORLD_HALF + this.cell * 0.5;
      for (let i = Math.max(0, i0); i <= Math.min(this.n - 1, i1); i++) {
        const px = (i - 1) * this.cell - WORLD_HALF + this.cell * 0.5;
        const ox = px - cx;
        const oz = pz - cz;
        // Inverse of rectFootprint's mapping.
        const lx = ox * cs - oz * sn;
        const lz = ox * sn + oz * cs;
        if (Math.abs(lx) <= hw && Math.abs(lz) <= hd) this.data[j * this.n + i] |= bit;
      }
    }
  }

  stampDisc(cx: number, cz: number, r: number, bit: number): void {
    const i0 = Math.max(0, this.ix(cx - r));
    const i1 = Math.min(this.n - 1, this.ix(cx + r));
    const j0 = Math.max(0, this.ix(cz - r));
    const j1 = Math.min(this.n - 1, this.ix(cz + r));
    const r2 = r * r;
    for (let j = j0; j <= j1; j++) {
      const pz = (j - 1) * this.cell - WORLD_HALF + this.cell * 0.5;
      for (let i = i0; i <= i1; i++) {
        const px = (i - 1) * this.cell - WORLD_HALF + this.cell * 0.5;
        if ((px - cx) ** 2 + (pz - cz) ** 2 <= r2) this.data[j * this.n + i] |= bit;
      }
    }
  }

  stampPolygon(ring: ReadonlyArray<Vec2>, bit: number): void {
    let x0 = Infinity; let x1 = -Infinity; let z0 = Infinity; let z1 = -Infinity;
    for (const v of ring) {
      if (v.x < x0) x0 = v.x;
      if (v.x > x1) x1 = v.x;
      if (v.z < z0) z0 = v.z;
      if (v.z > z1) z1 = v.z;
    }
    const i0 = Math.max(0, this.ix(x0));
    const i1 = Math.min(this.n - 1, this.ix(x1));
    const j0 = Math.max(0, this.ix(z0));
    const j1 = Math.min(this.n - 1, this.ix(z1));
    for (let j = j0; j <= j1; j++) {
      const pz = (j - 1) * this.cell - WORLD_HALF + this.cell * 0.5;
      for (let i = i0; i <= i1; i++) {
        const px = (i - 1) * this.cell - WORLD_HALF + this.cell * 0.5;
        if (pointInRing(ring, px, pz)) this.data[j * this.n + i] |= bit;
      }
    }
  }

  /** True when ANY cell of the oriented rect carries one of `bits`. */
  rectHits(cx: number, cz: number, w: number, d: number, rot: number, bits: number): boolean {
    const cs = Math.cos(rot);
    const sn = Math.sin(rot);
    const steps = (v: number): number => Math.max(1, Math.round(v / this.cell));
    const nu = steps(w);
    const nv = steps(d);
    for (let u = 0; u <= nu; u++) {
      const lx = (u / nu - 0.5) * w;
      for (let v = 0; v <= nv; v++) {
        const lz = (v / nv - 0.5) * d;
        const px = cx + lx * cs + lz * sn;
        const pz = cz - lx * sn + lz * cs;
        if ((this.at(px, pz) & bits) !== 0) return true;
      }
    }
    return false;
  }
}

export function pointInRing(ring: ReadonlyArray<Vec2>, x: number, z: number): boolean {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const a = ring[i];
    const b = ring[j];
    if ((a.z > z) !== (b.z > z)
      && x < ((b.x - a.x) * (z - a.z)) / (b.z - a.z) + a.x) inside = !inside;
  }
  return inside;
}

