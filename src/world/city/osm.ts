export class OsmCity {
  readonly nodes: OsmNode[] = [];
  readonly edges: OsmEdge[] = [];
  readonly footprints: OsmFootprint[] = [];
  readonly parks: OsmArea[] = [];
  readonly squares: OsmSquare[] = [];
  readonly trams: Vec2[][] = [];
  /** Named buildings worth putting on the map. */
  readonly places: Array<{ name: string; x: number; z: number; radius: number; kind: string }> = [];

  readonly mask = new OccupancyMask(CELL);
  readonly cover = new OccupancyMask(COVER_CELL);

  /** Real building centroids, hashed, for sampling the local storey count. */
  private levelHash = new Map<number, Array<{ x: number; z: number; levels: number }>>();
  private static readonly LEVEL_CELL = 120;

  stats = {
    ways: 0, nodes: 0, edges: 0, footprints: 0, parks: 0, dropped: 0,
    roadKm: 0, generalised: 0,
    /** Survey outlines whose sub-decimetre noise was removed before extrusion. */
    sanitised: 0,
    /** Footprints backed off from a compressed carriageway/square instead of intersecting it. */
    clearanceAdjusted: 0,
    /** Clear footprints moved a few metres into their block to preserve a named street wall. */
    clearanceShifted: 0,
  };

  /** True where the survey describes the city, so the grid must stand aside. */
  covered(x: number, z: number): boolean {
    return this.cover.has(x, z, Cell.road);
  }

  isCarriageway(x: number, z: number): boolean {
    return this.mask.has(x, z, Cell.road);
  }

  /**
   * Storey count of the real buildings around a point, for infill that has to
   * agree with its neighbours. Falls back to 0 when nothing is near.
   */
  levelsNear(x: number, z: number): number {
    const c = OsmCity.LEVEL_CELL;
    const i = Math.floor(x / c);
    const j = Math.floor(z / c);
    let sum = 0;
    let n = 0;
    let best = Infinity;
    let bestLv = 0;
    for (let di = -1; di <= 1; di++) {
      for (let dj = -1; dj <= 1; dj++) {
        const list = this.levelHash.get((i + di) * 100003 + (j + dj));
        if (!list) continue;
        for (const e of list) {
          const d2 = (e.x - x) ** 2 + (e.z - z) ** 2;
          if (d2 > 200 * 200) continue;
          sum += e.levels;
          n++;
          if (d2 < best) { best = d2; bestLv = e.levels; }
        }
      }
    }
    if (!n) return 0;
    // Weighted toward the nearest neighbour so a lone tower does not lift a
    // whole street, but a street of P+4 keeps its infill at P+4.
    return (sum / n) * 0.45 + bestLv * 0.55;
  }

  addLevelSample(x: number, z: number, levels: number): void {
    const c = OsmCity.LEVEL_CELL;
    const key = Math.floor(x / c) * 100003 + Math.floor(z / c);
    let list = this.levelHash.get(key);
    if (!list) this.levelHash.set(key, (list = []));
    list.push({ x, z, levels });
  }
}

