function toRing(raw: Array<[number, number]>): Vec2[] {
  const out: Vec2[] = [];
  for (const p of raw) out.push({ x: toWorldX(p[0]), z: toWorldZ(p[1]) });
  // OSM closes its rings; the builders do not want the duplicate.
  while (out.length > 1) {
    const a = out[0];
    const b = out[out.length - 1];
    if (Math.hypot(a.x - b.x, a.z - b.z) < 0.05) out.pop();
    else break;
  }
  // Normalise to the clockwise-from-above winding the builders assume.
  if (signedArea(out) > 0) out.reverse();
  return out;
}

export function centroid(ring: ReadonlyArray<Vec2>): Vec2 {
  let x = 0;
  let z = 0;
  for (const v of ring) { x += v.x; z += v.z; }
  return { x: x / ring.length, z: z / ring.length };
}

function ringBounds(ring: ReadonlyArray<Vec2>): Rect {
  let x0 = Infinity; let x1 = -Infinity; let z0 = Infinity; let z1 = -Infinity;
  for (const v of ring) {
    if (v.x < x0) x0 = v.x;
    if (v.x > x1) x1 = v.x;
    if (v.z < z0) z0 = v.z;
    if (v.z > z1) z1 = v.z;
  }
  return { x0, z0, x1, z1 };
}

function overlapsWorld(b: Rect): boolean {
  return b.x1 > -EDGE && b.x0 < EDGE && b.z1 > -EDGE && b.z0 < EDGE;
}

/** Sutherland–Hodgman against the map square. */
function clipRingToWorld(ring: ReadonlyArray<Vec2>): Vec2[] {
  let poly = ring.slice();
  const planes: Array<[number, number, number]> = [
    [1, 0, -EDGE], [-1, 0, -EDGE], [0, 1, -EDGE], [0, -1, -EDGE],
  ];
  for (const [nx, nz, off] of planes) {
    const next: Vec2[] = [];
    for (let i = 0; i < poly.length; i++) {
      const a = poly[i];
      const b = poly[(i + 1) % poly.length];
      const da = nx * a.x + nz * a.z + off;
      const db = nx * b.x + nz * b.z + off;
      if (da <= 0) next.push(a);
      if ((da <= 0) !== (db <= 0)) {
        const t = da / (da - db);
        next.push({ x: a.x + (b.x - a.x) * t, z: a.z + (b.z - a.z) * t });
      }
    }
    poly = next;
    if (!poly.length) return poly;
  }
  return poly;
}

/**
 * Minimum-area oriented bounding box, tested against every edge direction.
 * The angle is returned in `rectFootprint`'s convention, so the grammar can be
 * handed `{cx, cz, w, d, rot}` and produce a plot that sits on its real street.
 */
export function minAreaRect(
  ring: ReadonlyArray<Vec2>,
): { cx: number; cz: number; w: number; d: number; rot: number } {
  let best = { cx: 0, cz: 0, w: 1, d: 1, rot: 0, area: Infinity };
  for (let i = 0; i < ring.length; i++) {
    const a = ring[i];
    const b = ring[(i + 1) % ring.length];
    const dx = b.x - a.x;
    const dz = b.z - a.z;
    const len = Math.hypot(dx, dz);
    if (len < 0.2) continue;
    const ex = dx / len;
    const ez = dz / len;
    // local +x = (cos, -sin) -> cos = ex, sin = -ez.  local +z = (sin, cos).
    const fx = -ez;
    const fz = ex;
    let u0 = Infinity; let u1 = -Infinity; let v0 = Infinity; let v1 = -Infinity;
    for (const p of ring) {
      const u = p.x * ex + p.z * ez;
      const v = p.x * fx + p.z * fz;
      if (u < u0) u0 = u;
      if (u > u1) u1 = u;
      if (v < v0) v0 = v;
      if (v > v1) v1 = v;
    }
    const w = u1 - u0;
    const dd = v1 - v0;
    const area = w * dd;
    if (area < best.area) {
      const uc = (u0 + u1) / 2;
      const vc = (v0 + v1) / 2;
      best = {
        cx: ex * uc + fx * vc,
        cz: ez * uc + fz * vc,
        w, d: dd,
        rot: Math.atan2(-ez, ex),
        area,
      };
    }
  }
  return { cx: best.cx, cz: best.cz, w: best.w, d: best.d, rot: best.rot };
}

/** Class spec lookup, for the street builder. */
export function classSpec(cls: RoadClass): ClassSpec {
  return CLASS[cls];
}
