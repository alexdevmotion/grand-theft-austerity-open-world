/** Margin outside the map edge that geometry may still be built into. */
const EDGE = WORLD_HALF - 6;

function inWorld(x: number, z: number): boolean {
  return x > -EDGE && x < EDGE && z > -EDGE && z < EDGE;
}

export function buildOsmCity(opt: OsmCityOptions): OsmCity {
  const city = new OsmCity();
  const d = doc();

  buildNetwork(city, d.roads);
  stampReserved(city, opt.reserved);
  stampAuthoredAxes(city);
  buildGreen(city, d.parks, d.squares);
  squaresFromRoads(city, d.roads);
  buildFootprints(city, d.buildings);
  buildTrams(city, d.trams);

  return city;
}

/**
 * The two authored boulevards are laid by the grid, not by the survey, so the
 * survey has to be told they are there — otherwise a real footprint lands in
 * the middle of the 42 m carriageway Casa Constructorilor's forecourt opens on.
 */
function stampAuthoredAxes(city: OsmCity): void {
  const w = 42;
  const walk = 9.5;
  const span = WORLD_HALF * 2;
  city.mask.stampRect(AXIS_X, 0, w, span, 0, Cell.road);
  city.mask.stampRect(0, AXIS_Z, span, w, 0, Cell.road);
  city.mask.stampRect(AXIS_X, 0, w + walk * 2, span, 0, Cell.walk);
  city.mask.stampRect(0, AXIS_Z, span, w + walk * 2, 0, Cell.walk);
}

/* ---------------- road network ---------------- */

function classOf(cls: string): RoadClass {
  switch (cls) {
    case 'primary': case 'secondary': case 'tertiary':
    case 'residential': case 'pedestrian':
      return cls;
    default:
      return 'residential';
  }
}

function widthOf(name: string | null, cls: RoadClass, lanes: number | null): number {
  const spec = CLASS[cls];
  if (name) {
    for (const [re, w] of GRAND) if (re.test(name)) return w;
  }
  if (cls === 'pedestrian') return 0;
  if (lanes && lanes > 0) {
    return Math.max(spec.carriage * 0.8, Math.min(spec.carriage * 1.6, lanes * 3.0 + 1.2));
  }
  return spec.carriage;
}

/**
 * The two authored boulevards the story is staged on. Real ways that run along
 * them are dropped rather than drawn twice: the grid still lays these two, at
 * their authored 42 m, because Casa Constructorilor's forecourt, the Dacia's
 * kerbside slot and the Parliament axis are all measured against them.
 */
const AXIS_KEEPOUT = 15;

function onAuthoredAxis(
  ax: number, az: number, bx: number, bz: number,
): boolean {
  const mx = (ax + bx) / 2;
  const mz = (az + bz) / 2;
  const dx = bx - ax;
  const dz = bz - az;
  const len = Math.hypot(dx, dz) || 1;
  // Near-parallel and close to the centreline.
  if (Math.abs(mx - AXIS_X) < AXIS_KEEPOUT && Math.abs(dz / len) > 0.85) return true;
  if (Math.abs(mz - AXIS_Z) < AXIS_KEEPOUT && Math.abs(dx / len) > 0.85) return true;
  return false;
}

function buildNetwork(city: OsmCity, roads: RawRoad[]): void {
  /* Junction detection happens in SOURCE coordinates: OSM ways share the exact
   * node coordinates where they meet, and rounding after the transform would
   * merge distinct nodes on the compressed map. */
  const shared = new Map<string, number>();
  const key = (p: [number, number]): string => `${p[0].toFixed(1)},${p[1].toFixed(1)}`;
  for (const r of roads) {
    for (const p of r.path) shared.set(key(p), (shared.get(key(p)) ?? 0) + 1);
  }

  const nodeAt = new Map<string, number>();
  const nodeKey = (x: number, z: number): string =>
    `${Math.round(x / 0.6)},${Math.round(z / 0.6)}`;

  const nodeId = (x: number, z: number, rank: StreetRank, patch: number): number => {
    const k = nodeKey(x, z);
    const found = nodeAt.get(k);
    if (found !== undefined) {
      const n = city.nodes[found];
      if (rank > n.rank) n.rank = rank;
      if (patch > n.patch) n.patch = patch;
      return found;
    }
    const id = city.nodes.length;
    city.nodes.push({ x, z, rank, patch, edges: [] });
    nodeAt.set(k, id);
    return id;
  };

  /*
   * CARTOGRAPHIC GENERALISATION — the pass that makes a compressed map read.
   *
   * A lane stays 3 m wide while the map shrinks to 60%, so the street network
   * eats proportionally more ground than it does in life. Imported literally,
   * central Bucharest came out as a third carriageway by area with the blocks
   * between it too thin to carry a street wall — more road than city.
   *
   * The fix is the one a cartographer uses when a map is reduced: drop the
   * streets that no longer earn their space. Ways are laid in order of
   * importance and a minor one is skipped where its corridor is ALREADY
   * tarmac — the parallel service road beside a boulevard, the second half of
   * a dual carriageway, the inner ring of a roundabout, the parking aisle
   * behind a block. Nothing that carries the shape of the city is lost, and
   * the blocks get their land back.
   */
  const RANK_ORDER: RoadClass[] = ['primary', 'secondary', 'tertiary', 'residential', 'pedestrian'];
  const ordered = roads.slice().sort(
    (a, b) => RANK_ORDER.indexOf(classOf(a.cls)) - RANK_ORDER.indexOf(classOf(b.cls)),
  );

  const alreadyPaved = (a: Vec2, b: Vec2): boolean => {
    let on = 0;
    const n = 5;
    for (let i = 0; i <= n; i++) {
      const t = i / n;
      if (city.mask.has(a.x + (b.x - a.x) * t, a.z + (b.z - a.z) * t, Cell.road)) on++;
    }
    return on > n * 0.6;
  };

  for (const r of ordered) {
    const cls = classOf(r.cls);
    const name = r.name ?? null;
    const width = widthOf(name, cls, r.lanes ?? null);
    const spec = CLASS[cls];
    const walk = spec.walk;
    const lanes = Math.max(1, Math.round((r.lanes ?? 2) / (r.oneway ? 1 : 2)));

    // Transform, remembering which vertices are shared junctions.
    const pts: Vec2[] = [];
    const forced: boolean[] = [];
    for (const p of r.path) {
      pts.push({ x: toWorldX(p[0]), z: toWorldZ(p[1]) });
      forced.push((shared.get(key(p)) ?? 0) > 1);
    }

    // Split into runs that lie inside the map.
    let run: Vec2[] = [];
    let runForced: boolean[] = [];
    const flush = (): void => {
      if (run.length >= 2) emitWay(run, runForced);
      run = [];
      runForced = [];
    };
    for (let i = 0; i < pts.length; i++) {
      if (inWorld(pts[i].x, pts[i].z)) {
        run.push(pts[i]);
        runForced.push(forced[i]);
      } else flush();
    }
    flush();
    city.stats.ways++;

    function emitWay(way: Vec2[], force: boolean[]): void {
      const keep = simplify(way, force, 1.6, 9, 56);
      for (let i = 0; i + 1 < keep.length; i++) {
        const a = way[keep[i]];
        const b = way[keep[i + 1]];
        const len = Math.hypot(b.x - a.x, b.z - a.z);
        if (len < 0.5) continue;
        if (onAuthoredAxis(a.x, a.z, b.x, b.z)) continue;
        if (spec.rank === 0 && alreadyPaved(a, b)) { city.stats.generalised++; continue; }
        const na = nodeId(a.x, a.z, spec.rank, width / 2);
        const nb = nodeId(b.x, b.z, spec.rank, width / 2);
        if (na === nb) continue;
        const id = city.edges.length;
        city.edges.push({
          a: na, b: nb, cls, name, width, walk, rank: spec.rank,
          lanes, oneway: !!r.oneway, tram: false, length: len,
        });
        city.nodes[na].edges.push(id);
        city.nodes[nb].edges.push(id);
        city.stats.roadKm += len / 1000;
        // Claim the corridor immediately so the next minor way sees it.
        if (width > 0) city.mask.stampSegment(a.x, a.z, b.x, b.z, width, Cell.road);
      }
    }
  }

  // Footway corridors and coverage. Carriageways were stamped as they were
  // laid, because the generalisation pass above reads them back.
  for (const e of city.edges) {
    const a = city.nodes[e.a];
    const b = city.nodes[e.b];
    city.mask.stampSegment(a.x, a.z, b.x, b.z, e.width + e.walk * 2, Cell.walk);
    if (e.rank >= 1) city.mask.stampSegment(a.x, a.z, b.x, b.z, e.width + 130, Cell.major);
    city.cover.stampSegment(a.x, a.z, b.x, b.z, e.width + COVER_REACH * 2, Cell.road);
  }

  city.stats.nodes = city.nodes.length;
  city.stats.edges = city.edges.length;
}

/**
 * Douglas–Peucker, then a spacing pass.
 *
 * The graph and the ribbons share one vertex list, so the tolerance has to
 * serve both: too coarse and Calea Victoriei's curve becomes a dogleg, too fine
 * and A* is walking ten thousand nodes. Junction vertices are always kept —
 * they are what makes the two ways meet in the graph at all.
 */
function simplify(
  pts: ReadonlyArray<Vec2>,
  forced: ReadonlyArray<boolean>,
  tol: number,
  minSpacing: number,
  maxSpacing: number,
): number[] {
  const n = pts.length;
  const keep = new Uint8Array(n);
  keep[0] = 1;
  keep[n - 1] = 1;
  for (let i = 0; i < n; i++) if (forced[i]) keep[i] = 1;

  // DP between consecutive forced anchors.
  const anchors: number[] = [];
  for (let i = 0; i < n; i++) if (keep[i]) anchors.push(i);
  for (let k = 0; k + 1 < anchors.length; k++) {
    dp(pts, anchors[k], anchors[k + 1], tol, keep);
  }

  // Spacing: drop non-forced vertices that crowd, insert nothing (a long
  // straight run needs no extra nodes; the ribbon is straight anyway).
  const out: number[] = [];
  let lastX = 0;
  let lastZ = 0;
  for (let i = 0; i < n; i++) {
    if (!keep[i]) continue;
    if (out.length && !forced[i] && i !== n - 1) {
      if (Math.hypot(pts[i].x - lastX, pts[i].z - lastZ) < minSpacing) continue;
    }
    out.push(i);
    lastX = pts[i].x;
    lastZ = pts[i].z;
  }
  void maxSpacing;
  return out;
}

function dp(
  pts: ReadonlyArray<Vec2>, i0: number, i1: number, tol: number, keep: Uint8Array,
): void {
  if (i1 - i0 < 2) return;
  const a = pts[i0];
  const b = pts[i1];
  const dx = b.x - a.x;
  const dz = b.z - a.z;
  const len = Math.hypot(dx, dz) || 1;
  let worst = 0;
  let at = -1;
  for (let i = i0 + 1; i < i1; i++) {
    const p = pts[i];
    const dist = Math.abs((p.x - a.x) * dz - (p.z - a.z) * dx) / len;
    if (dist > worst) { worst = dist; at = i; }
  }
  if (worst <= tol || at < 0) return;
  keep[at] = 1;
  dp(pts, i0, at, tol, keep);
  dp(pts, at, i1, tol, keep);
}

/* ---------------- reserved ground ---------------- */

function stampReserved(city: OsmCity, rects: Rect[]): void {
  for (const r of rects) {
    city.mask.stampRect(
      (r.x0 + r.x1) / 2, (r.z0 + r.z1) / 2,
      r.x1 - r.x0, r.z1 - r.z0, 0, Cell.reserved,
    );
  }
}

function isReserved(city: OsmCity, x: number, z: number): boolean {
  return city.mask.has(x, z, Cell.reserved);
}

/* ---------------- parks and squares ---------------- */

function buildGreen(city: OsmCity, parks: RawArea[], squares: RawSquare[]): void {
  for (const p of parks) {
    const ring = toRing(p.ring);
    if (ring.length < 3) continue;
    const b = ringBounds(ring);
    if (!overlapsWorld(b)) continue;
    // A park cut in half by the map edge is worse than no park.
    const clipped = clipRingToWorld(ring);
    if (clipped.length < 3) continue;
    if (Math.abs(signedArea(clipped)) < 340) continue;
    city.parks.push({ ring: clipped, name: p.name ?? null });
    city.mask.stampPolygon(clipped, Cell.green);
  }
  city.stats.parks = city.parks.length;

  for (const s of squares) {
    let x: number;
    let z: number;
    if (s.ring && s.ring.length) {
      const ring = toRing(s.ring);
      const b = ringBounds(ring);
      x = (b.x0 + b.x1) / 2;
      z = (b.z0 + b.z1) / 2;
    } else if (s.x !== undefined && s.z !== undefined) {
      x = toWorldX(s.x);
      z = toWorldZ(s.z);
    } else continue;
    if (!inWorld(x, z)) continue;
    const radius = 38;
    city.squares.push({ name: s.name, x, z, radius });
    city.mask.stampDisc(x, z, radius, Cell.square);
  }

}

/**
 * The squares that matter most — Victoriei, Universității, Romană, Revoluției —
 * are NOT areas in the survey. OSM maps a Bucharest square as the bundle of
 * carriageways named after it, so they arrive as roads and would have been
 * paved as ordinary tarmac. Recovering them is the whole point of the import,
 * so every road whose name begins "Piața" is collapsed to its centroid and
 * given a stone deck sized to the spread of its own carriageways.
 */
function squaresFromRoads(city: OsmCity, roads: RawRoad[]): void {
  const groups = new Map<string, Vec2[]>();
  for (const r of roads) {
    if (!r.name || !/^Piața /.test(r.name)) continue;
    let list = groups.get(r.name);
    if (!list) groups.set(r.name, (list = []));
    for (const p of r.path) list.push({ x: toWorldX(p[0]), z: toWorldZ(p[1]) });
  }
  for (const [name, pts] of groups) {
    const c = centroid(pts);
    if (!inWorld(c.x, c.z)) continue;
    if (isReserved(city, c.x, c.z)) continue;
    if (city.squares.some((s) => Math.hypot(s.x - c.x, s.z - c.z) < 70)) continue;
    // Radius from the spread of the square's own carriageways, but never so
    // large that it swallows the blocks around it.
    let rms = 0;
    for (const p of pts) rms += (p.x - c.x) ** 2 + (p.z - c.z) ** 2;
    // Capped hard. A square is a room in the city, not a field: at 66 m the
    // deck swallowed the blocks around Piața Universității and pushed its own
    // frontage back until the square had no walls at all.
    const radius = Math.max(22, Math.min(44, Math.sqrt(rms / pts.length) * 0.7));
    city.squares.push({ name, x: c.x, z: c.z, radius });
    city.mask.stampDisc(c.x, c.z, radius, Cell.square);
  }
}

/* ---------------- footprints ---------------- */

function buildFootprints(city: OsmCity, buildings: RawBuilding[]): void {
  for (const b of buildings) {
    let ring = toRing(b.ring);
    if (ring.length < 3) continue;
    const bounds = ringBounds(ring);
    if (!overlapsWorld(bounds)) continue;

    // Grow about the centroid to recover human proportions after the map
    // compression, backing off in steps if the growth would eat the street.
    const c = centroid(ring);
    let grown = ring;
    for (const g of [OSM_FIT.footprintGrow, 1.15, 1.0]) {
      grown = g === 1 ? ring : ring.map((v) => ({
        x: c.x + (v.x - c.x) * g,
        z: c.z + (v.z - c.z) * g,
      }));
      if (!ringHitsRoad(city, grown)) break;
    }
    ring = grown;

    const area = Math.abs(signedArea(ring));
    if (area < 34) { city.stats.dropped++; continue; }

    const cc = centroid(ring);
    if (!inWorld(cc.x, cc.z)) { city.stats.dropped++; continue; }
    if (isReserved(city, cc.x, cc.z)) { city.stats.dropped++; continue; }
    if (city.mask.has(cc.x, cc.z, Cell.road)) { city.stats.dropped++; continue; }

    const box = minAreaRect(ring);
    const face = facingOf(city, cc.x, cc.z, box.rot);

    const fp: OsmFootprint = {
      ring,
      cx: box.cx, cz: box.cz, w: box.w, d: box.d, rot: box.rot,
      fx: face.x, fz: face.z,
      levels: Math.max(1, b.levels),
      name: b.name ?? null,
      kind: b.kind ?? 'yes',
      area,
    };
    city.footprints.push(fp);
    city.mask.stampPolygon(ring, Cell.built);
    city.addLevelSample(cc.x, cc.z, fp.levels);

    if (fp.name && isPlaceName(fp.name, area, fp.kind)) {
      city.places.push({
        name: fp.name, x: cc.x, z: cc.z,
        radius: Math.max(18, Math.sqrt(area) * 0.6),
        kind: fp.kind,
      });
    }
  }
  city.stats.footprints = city.footprints.length;
}

/**
 * Which named buildings deserve a pin on the map.
 *
 * OSM names a great deal that a player would never call a place: block
 * numbers, heating substations, a supermarket unit, "Corp C", "sala de sport".
 * The map is a navigation aid, so the bar is a building someone would give as
 * a direction — a palace, a theatre, a church, a ministry, a hotel — or simply
 * something big enough to be a landmark by mass alone.
 */
const NOT_A_PLACE = /^(bl\.?|bloc|sc\.?|scara|tronson|p\d+$|punct termic|corp\b|cladire|clădire|anexa|anexă|garaj|magazie|depozit|hala|hală|sala\b|parcare)/i;
const IS_A_PLACE = /^(pala|palat|catedral|biseric|teatr|muzeu|hotel|banca|banc[ăa]|universit|colegiu|liceu|academia|ateneu|spital|primăria|ministerul|tribunal|gara |institut|casa |sala palatului|opera)/i;

function isPlaceName(n: string, area: number, kind: string): boolean {
  const t = n.trim();
  if (t.length < 4) return false;
  if (NOT_A_PLACE.test(t)) return false;
  if (IS_A_PLACE.test(t)) return true;
  if (kind === 'church' || kind === 'cathedral' || kind === 'university'
    || kind === 'public' || kind === 'government' || kind === 'hotel') return true;
  // Otherwise it has to earn it by mass.
  return area > 1600;
}

function ringHitsRoad(city: OsmCity, ring: ReadonlyArray<Vec2>): boolean {
  for (const v of ring) if (city.mask.has(v.x, v.z, Cell.road)) return true;
  return false;
}

/**
 * Which way this plot faces. The grammar puts the entrance, the balconies and
 * the shopfront on this side, so getting it wrong turns a street wall inside
 * out. Take the nearest carriageway within reach, otherwise fall back to the
 * long axis of the plot.
 */
function facingOf(city: OsmCity, cx: number, cz: number, rot: number): Vec2 {
  const cs = Math.cos(rot);
  const sn = Math.sin(rot);
  // The two candidate faces are along the OBB's local +/- z axis, i.e. the
  // long-side normals: local +z maps to (sin, cos).
  const cand: Vec2[] = [
    { x: sn, z: cs }, { x: -sn, z: -cs },
    { x: cs, z: -sn }, { x: -cs, z: sn },
  ];
  let best = cand[0];
  let bestD = Infinity;
  for (const c of cand) {
    for (let t = 6; t <= 46; t += 4) {
      if (city.mask.has(cx + c.x * t, cz + c.z * t, Cell.road)) {
        if (t < bestD) { bestD = t; best = c; }
        break;
      }
    }
  }
  return best;
}

/* ---------------- trams ---------------- */

function buildTrams(city: OsmCity, trams: Array<{ path: Array<[number, number]> }>): void {
  for (const t of trams) {
    let run: Vec2[] = [];
    const flush = (): void => {
      if (run.length >= 2) {
        const forced = run.map((_, i) => i === 0 || i === run.length - 1);
        const keep = simplify(run, forced, 1.4, 8, 60);
        city.trams.push(keep.map((i) => run[i]));
      }
      run = [];
    };
    for (const p of t.path) {
      const x = toWorldX(p[0]);
      const z = toWorldZ(p[1]);
      if (inWorld(x, z)) run.push({ x, z });
      else flush();
    }
    flush();
  }
}

